"""Rebuild public/index.html and the vote whitelist from roster.txt.
Run from the repo root:  python3 source/build.py"""
import json, re, sys, unicodedata, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
data, cur = {}, None
for ln in (root / "source/roster.txt").read_text(encoding="utf-8").splitlines():
    if not ln.strip() or ln.startswith("#"): continue
    if ln.startswith("@"): cur = int(ln[1:]); data[cur] = []; continue
    t, d, g, p, w, o = [x.strip() for x in (ln.split("|") + [""] * 6)[:6]]
    data[cur].append([t, d, g, p or "Windows", "" if w == t else w, o])
def slug(t):
    t = unicodedata.normalize("NFKD", t).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", "-", t).strip("-")[:70]
ids, ok = {}, True
for y, gs in sorted(data.items()):
    want = None if y < 1984 else 15 if y < 2000 else 20
    s = [slug(g[0]) for g in gs]
    if len(set(s)) != len(s): print("Duplicate title in", y); ok = False
    if want and len(gs) != want: print(f"Note: {y} has {len(gs)} games (usual {want})")
    ids[str(y)] = s
    for g, i in zip(gs, s): g.insert(0, i)
# Built-in covers: source/covers.txt lines "year/id|https://upload.wikimedia.org/..." (made by the #covers page).
# A hand-set url: override in roster.txt always wins.
cov = root / "source/covers.txt"
nbuilt = 0
if cov.exists():
    look = {f"{y}/{g[0]}": g for y, gs in data.items() for g in gs}
    for ln in cov.read_text(encoding="utf-8").splitlines():
        if "|" not in ln: continue
        k, u = ln.split("|", 1); k, u = k.strip(), u.strip()
        g = look.get(k)
        if g and u.startswith("https://") and not g[6].startswith("url:") and g[6] != "none":
            g[6] = "url:" + u; nbuilt += 1
print("Built-in covers:", nbuilt)
html = (root / "source/template.html").read_text(encoding="utf-8")
html = html.replace("/*__DB__*/null", json.dumps(data, ensure_ascii=False, separators=(",", ":")))
(root / "public/index.html").write_text(html, encoding="utf-8")
(root / "netlify/functions/ids.mjs").write_text("// Generated by source/build.py. Valid game ids per year.\nexport default " + json.dumps(ids, separators=(",", ":")) + ";\n")
print("Built", sum(len(v) for v in data.values()), "games over", len(data), "years")
sys.exit(0 if ok else 1)
